"""Generate the firmware's offline landing page from the same PC renderer."""
from pathlib import Path
from studypet.screen_protocol import pack_pixels
from studypet.screen_render import prepare_font, waiting_page

image = waiting_page(prepare_font())
frame = pack_pixels(list(image.getdata()))
target = Path('firmware/usb-speaker/main/screen_waiting.h')
lines = ['// Generated by tools/generate_waiting_screen.py; do not edit.',
         '// Font: Noto Sans SC; see licenses/NotoSansSC-OFL.txt.',
         '#pragma once', '#include <stdint.h>', 'static const uint8_t screen_waiting[15000] = {']
for start in range(0, len(frame), 24):
    lines.append('    ' + ','.join(f'0x{v:02x}' for v in frame[start:start+24]) + ',')
lines.append('};')
target.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(target)
